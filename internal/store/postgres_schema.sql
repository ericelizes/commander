CREATE TRIGGER agent_state_state_event AFTER INSERT OR UPDATE OR DELETE ON agent_state FOR EACH ROW EXECUTE FUNCTION commander_state_event();
CREATE TRIGGER workstream_managers_state_event AFTER INSERT OR UPDATE OR DELETE ON workstream_managers FOR EACH ROW EXECUTE FUNCTION commander_state_event();
CREATE TRIGGER bead_ranks_state_event AFTER INSERT OR UPDATE OR DELETE ON bead_ranks FOR EACH ROW EXECUTE FUNCTION commander_state_event();
CREATE TRIGGER workstream_ranks_state_event AFTER INSERT OR UPDATE OR DELETE ON workstream_ranks FOR EACH ROW EXECUTE FUNCTION commander_state_event();
CREATE TRIGGER needs_you_state_event AFTER INSERT OR UPDATE OR DELETE ON needs_you FOR EACH ROW EXECUTE FUNCTION commander_state_event();
CREATE TRIGGER needs_resolutions_state_event AFTER INSERT OR UPDATE OR DELETE ON needs_resolutions FOR EACH ROW EXECUTE FUNCTION commander_state_event();
