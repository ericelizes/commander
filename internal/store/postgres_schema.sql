-- PostgreSQL schema corresponding to SQLite schema 22.
CREATE TABLE projects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  type TEXT NOT NULL CHECK(type IN ('code', 'knowledge')),
  path TEXT NOT NULL,
  activated_at BIGINT NOT NULL,
  status TEXT NOT NULL DEFAULT 'active'
, repo_path TEXT NOT NULL DEFAULT '');

CREATE TABLE objectives (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description_path TEXT,
  status TEXT NOT NULL DEFAULT 'open',
  created_at BIGINT NOT NULL,
  closed_at BIGINT
);

CREATE TABLE objective_tasks (
  objective_id BIGINT NOT NULL REFERENCES objectives(id),
  project_id BIGINT NOT NULL REFERENCES projects(id),
  task_bead_id TEXT NOT NULL,
  is_derived BIGINT NOT NULL DEFAULT 0,
  derived_from_task_bead_id TEXT,
  created_at BIGINT NOT NULL,
  PRIMARY KEY (objective_id, project_id, task_bead_id)
);

CREATE TABLE cost_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL REFERENCES projects(id),
  task_bead_id TEXT,
  agent_name TEXT NOT NULL,
  event_type TEXT NOT NULL,
  reason TEXT,
  delta_usd DOUBLE PRECISION DEFAULT 0,
  delta_tokens BIGINT DEFAULT 0,
  occurred_at BIGINT NOT NULL
);

CREATE TABLE agent_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL REFERENCES projects(id),
  task_bead_id TEXT NOT NULL,
  agent_name TEXT NOT NULL,
  opencode_session_id TEXT NOT NULL,
  container_id TEXT,
  tmux_pane_id TEXT,
  spawn_time BIGINT NOT NULL,
  tokens_used BIGINT NOT NULL DEFAULT 0,
  usd_used DOUBLE PRECISION NOT NULL DEFAULT 0,
  consecutive_failures BIGINT NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'running'
, active_at BIGINT NOT NULL DEFAULT 0, quiet_told BIGINT NOT NULL DEFAULT 0, model TEXT NOT NULL DEFAULT '', worktree_path TEXT);

CREATE TABLE tui_state (
  id BIGINT PRIMARY KEY CHECK(id=1),
  current_view TEXT NOT NULL DEFAULT 'commander',
  selected_project_id BIGINT,
  selected_task_bead_id TEXT,
  scroll_state TEXT
);

CREATE TABLE am_agents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  am_project_key TEXT NOT NULL,
  role TEXT NOT NULL,
  am_name TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  UNIQUE(am_project_key, role)
);

CREATE TABLE workstream_ranks (
  project_id BIGINT NOT NULL,
  bead_id TEXT NOT NULL,
  rank BIGINT NOT NULL,
  PRIMARY KEY (project_id, bead_id)
);

CREATE TABLE workstream_managers (
  project_id BIGINT NOT NULL,
  workstream_bead_id TEXT NOT NULL,
  am_role TEXT NOT NULL UNIQUE,
  session_file TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  PRIMARY KEY (project_id, workstream_bead_id)
);

CREATE TABLE inspector_tabs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL,
  workstream_bead_id TEXT NOT NULL,
  position BIGINT NOT NULL,
  title TEXT NOT NULL,
  kind TEXT NOT NULL,                     -- url | cmd | (v2) term | image
  target TEXT NOT NULL,                   -- URL, shell command, or path
  renderer TEXT NOT NULL DEFAULT '',      -- '' = auto-detect from target
  refresh_secs BIGINT NOT NULL DEFAULT 60,
  added_by TEXT NOT NULL,                 -- 'user' | am role e.g. manager-<bead>
  created_at BIGINT NOT NULL,
  UNIQUE (project_id, workstream_bead_id, target)
);

CREATE TABLE inspector_state (
  project_id BIGINT NOT NULL,
  workstream_bead_id TEXT NOT NULL,
  active_tab_id BIGINT,
  cache_json TEXT,
  cached_at BIGINT,
  PRIMARY KEY (project_id, workstream_bead_id)
);

CREATE TABLE needs_you (
  project_id BIGINT NOT NULL,
  bead_id TEXT NOT NULL,
  ask TEXT NOT NULL,
  note TEXT NOT NULL DEFAULT '',
  since BIGINT NOT NULL, decision TEXT NOT NULL DEFAULT '',
  PRIMARY KEY (project_id, bead_id)
);

CREATE TABLE agent_state (
  role TEXT PRIMARY KEY,
  state TEXT NOT NULL,           -- working | idle
  detail TEXT NOT NULL DEFAULT '', -- what it is doing: tool name and a short target
  since BIGINT NOT NULL,        -- when it entered this state
  updated BIGINT NOT NULL       -- last hook event, to spot a silent (dead/stuck) agent
);

CREATE TABLE gates (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  project_id BIGINT NOT NULL,
  bead_id    TEXT    NOT NULL,
  name       TEXT    NOT NULL,
  check_text TEXT    NOT NULL,           -- a shell command (auto) or a rule to verify (reviewer/user)
  verifier   TEXT    NOT NULL,           -- auto | reviewer:<login> | user
  status     TEXT    NOT NULL DEFAULT 'open',  -- open | passed | failed
  evidence   TEXT    NOT NULL DEFAULT '',
  by_who     TEXT    NOT NULL DEFAULT '',
  at         BIGINT NOT NULL DEFAULT 0,
  created    BIGINT NOT NULL,
  PRIMARY KEY (project_id, bead_id, name)
);

CREATE TABLE manager_checkins (
  role    TEXT    PRIMARY KEY,       -- manager-<workstream bead>
  due     BIGINT NOT NULL,          -- unix s of its next check-in
  checked BIGINT NOT NULL DEFAULT 0 -- unix s of the watch's last look at its Operators
);

CREATE TABLE watch_issues (
  key    TEXT    PRIMARY KEY,         -- <workstream bead>:<kind>[:<detail>]
  ws     TEXT    NOT NULL,            -- workstream bead id
  text   TEXT    NOT NULL,            -- "stalled: nobody on its open work"
  since  BIGINT NOT NULL,            -- unix s it began
  active BIGINT NOT NULL DEFAULT 0,  -- 1 once it has lasted long enough to matter
  told   BIGINT NOT NULL DEFAULT 0   -- 1 once Commander was told
);

CREATE TABLE chat_costs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
  role           TEXT    NOT NULL,
  session_id     TEXT    NOT NULL,
  total_usd      DOUBLE PRECISION    NOT NULL,           -- cumulative session cost after this turn
  delta_usd      DOUBLE PRECISION    NOT NULL,           -- this turn's cost
  input_tokens   BIGINT NOT NULL DEFAULT 0,
  output_tokens  BIGINT NOT NULL DEFAULT 0,
  cache_read     BIGINT NOT NULL DEFAULT 0,
  cache_create   BIGINT NOT NULL DEFAULT 0,
  occurred_at    BIGINT NOT NULL,           -- unix s
  UNIQUE (session_id, total_usd)
);

CREATE TABLE usage_turns (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
  turn_key     TEXT    NOT NULL UNIQUE,
  source       TEXT    NOT NULL,            -- chat | operator
  role         TEXT    NOT NULL,            -- commander, manager-<bead>, operator-<flat>
  runtime      TEXT    NOT NULL,            -- claude | codex
  account      TEXT    NOT NULL DEFAULT '', -- Claude account name, or codex
  model        TEXT    NOT NULL DEFAULT '',
  input_tokens BIGINT NOT NULL DEFAULT 0,
  output_tokens BIGINT NOT NULL DEFAULT 0,
  cache_read   BIGINT NOT NULL DEFAULT 0,
  cache_create BIGINT NOT NULL DEFAULT 0,
  usd          DOUBLE PRECISION    NOT NULL DEFAULT 0,
  occurred_at  BIGINT NOT NULL             -- unix s
);

CREATE TABLE usage_scan (
  path   TEXT    PRIMARY KEY,
  "offset" BIGINT NOT NULL DEFAULT 0,
  state  TEXT    NOT NULL DEFAULT ''
);

CREATE TABLE pitches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL,
  bead_id TEXT NOT NULL,
  version BIGINT NOT NULL,
  title TEXT NOT NULL,
  decision TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  answer TEXT NOT NULL DEFAULT '',
  answered_at BIGINT NOT NULL DEFAULT 0, basis TEXT,
  UNIQUE (project_id, bead_id, version)
);

CREATE TABLE needs_resolutions (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  project_id BIGINT NOT NULL REFERENCES projects(id),
  bead_id TEXT NOT NULL,
  generation TEXT NOT NULL,
  payload TEXT NOT NULL,
  state BIGINT NOT NULL DEFAULT 0,
  PRIMARY KEY(project_id, bead_id, generation)
);

CREATE TABLE board_since (
  key   TEXT    PRIMARY KEY, -- project:bead of the row
  state TEXT    NOT NULL,    -- kind|text it shows
  since BIGINT NOT NULL     -- unix s it began showing it
);

CREATE TABLE manager_unregistrations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL,
 bead_id TEXT NOT NULL,
 root_id TEXT NOT NULL,
 actor TEXT NOT NULL,
 manager_role TEXT NOT NULL,
 session_file TEXT NOT NULL,
 created_at BIGINT NOT NULL
);

CREATE TABLE bead_ranks (
  project_id BIGINT NOT NULL,
  bead_id TEXT NOT NULL,
  rank BIGINT NOT NULL,
  PRIMARY KEY (project_id, bead_id)
);

CREATE INDEX idx_chat_costs_role_time ON chat_costs(role, occurred_at);

CREATE INDEX idx_usage_turns_time ON usage_turns(occurred_at);

CREATE INDEX pitches_bead ON pitches(project_id, bead_id);


CREATE TABLE bead_tasks (
 project_id BIGINT NOT NULL REFERENCES projects(id),
 id TEXT NOT NULL,
 title TEXT NOT NULL,
 description TEXT NOT NULL DEFAULT '',
 acceptance_criteria TEXT NOT NULL DEFAULT '',
 notes TEXT NOT NULL DEFAULT '',
 status TEXT NOT NULL DEFAULT 'open',
 issue_type TEXT NOT NULL DEFAULT 'task',
 priority BIGINT NOT NULL DEFAULT 2 CHECK(priority BETWEEN 0 AND 4),
 labels JSONB NOT NULL DEFAULT '[]',
 parent_id TEXT,
 assigned_agent TEXT NOT NULL DEFAULT '',
 close_reason TEXT NOT NULL DEFAULT '',
 created_at TEXT NOT NULL,
 updated_at TEXT NOT NULL,
 deleted_at BIGINT,
 PRIMARY KEY(project_id,id),
 FOREIGN KEY(project_id,parent_id) REFERENCES bead_tasks(project_id,id) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX bead_tasks_parent ON bead_tasks(project_id,parent_id);
CREATE INDEX bead_tasks_status ON bead_tasks(project_id,status) WHERE deleted_at IS NULL;
CREATE INDEX bead_tasks_labels ON bead_tasks USING GIN(labels);
CREATE TABLE bead_dependencies (
 project_id BIGINT NOT NULL,
 issue_id TEXT NOT NULL,
 depends_on_id TEXT NOT NULL,
 type TEXT NOT NULL,
 PRIMARY KEY(project_id,issue_id,depends_on_id,type),
 FOREIGN KEY(project_id,issue_id) REFERENCES bead_tasks(project_id,id) DEFERRABLE INITIALLY DEFERRED,
 FOREIGN KEY(project_id,depends_on_id) REFERENCES bead_tasks(project_id,id) DEFERRABLE INITIALLY DEFERRED,
 CHECK(issue_id <> depends_on_id)
);
CREATE INDEX bead_dependencies_target ON bead_dependencies(project_id,depends_on_id);
CREATE TABLE bead_comments (
 project_id BIGINT NOT NULL,
 bead_id TEXT NOT NULL,
 id TEXT NOT NULL,
 author TEXT NOT NULL,
 text TEXT NOT NULL,
 created_at TEXT NOT NULL,
 PRIMARY KEY(project_id,bead_id,id),
 FOREIGN KEY(project_id,bead_id) REFERENCES bead_tasks(project_id,id) DEFERRABLE INITIALLY DEFERRED
);
CREATE TABLE state_events (
 seq BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 entity TEXT NOT NULL,
 operation TEXT NOT NULL,
 identity JSONB NOT NULL,
 delivered BOOLEAN NOT NULL DEFAULT FALSE,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX state_events_time ON state_events(occurred_at);
CREATE INDEX state_events_pending ON state_events(seq) WHERE NOT delivered;
CREATE FUNCTION commander_state_event() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE body JSONB;
BEGIN
 body := CASE WHEN TG_OP='DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
 INSERT INTO state_events(entity,operation,identity) VALUES(TG_TABLE_NAME,TG_OP,
  jsonb_strip_nulls(jsonb_build_object('project_id',body->'project_id','id',body->'id','bead_id',COALESCE(body->'bead_id',body->'task_bead_id',body->'workstream_bead_id'),'role',COALESCE(body->'role',body->'agent_name'))));
 PERFORM pg_notify('commander_state','changed');
 RETURN NULL;
END $$;

CREATE TRIGGER bead_tasks_state_event AFTER INSERT OR UPDATE OR DELETE ON bead_tasks FOR EACH ROW EXECUTE FUNCTION commander_state_event();
CREATE TRIGGER bead_dependencies_state_event AFTER INSERT OR UPDATE OR DELETE ON bead_dependencies FOR EACH ROW EXECUTE FUNCTION commander_state_event();
CREATE TRIGGER bead_comments_state_event AFTER INSERT OR UPDATE OR DELETE ON bead_comments FOR EACH ROW EXECUTE FUNCTION commander_state_event();
